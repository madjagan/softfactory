def inline(s: str) -> str:
    s = html.escape(s, quote=False)
    s = re.sub(r"`([^`]+)`", r"<code>\1</code>", s)
    s = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", s)
    s = re.sub(r"(?<![*\w])\*([^*]+)\*(?![*\w])", r"<em>\1</em>", s)
    s = re.sub(r"\[([^\]]+)\]\(([^)]+)\)", r'<a href="\2">\1</a>', s)
    return s


def render_md(text: str) -> str:
    out: list[str] = []
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1; continue
        if line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")]); i += 1
            body = [r for r in rows[1:] if not all(re.fullmatch(r":?-+:?", c or "-") for c in r)]
            out.append('<div class="tw"><table><thead><tr>' + "".join(f"<th>{inline(c)}</th>" for c in rows[0]) + "</tr></thead><tbody>")
            for r in body:
                out.append("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>")
            out.append("</tbody></table></div>"); continue
        m = re.match(r"^(#{1,4}) (.*)", line)
        if m:
            level = len(m.group(1)); title = m.group(2)
            slug = re.sub(r"[^a-z0-9]+", "-", re.sub(r"\*\*|`", "", title).lower()).strip("-")
            out.append(f'<h{level} id="{slug}">{inline(title)}</h{level}>'); i += 1; continue
        if re.match(r"^-{3,}\s*$", line):
            out.append("<hr>"); i += 1; continue
        if re.match(r"^(- |\d+\. )", line):
            ordered = bool(re.match(r"^\d+\. ", line)); items = []
            while i < len(lines) and re.match(r"^(- |\d+\. )", lines[i]):
                item = re.sub(r"^(- |\d+\. )", "", lines[i]); i += 1
                while i < len(lines) and lines[i].startswith("  ") and lines[i].strip():
                    item += " " + lines[i].strip(); i += 1
                items.append(item)
            tag = "ol" if ordered else "ul"
            out.append(f"<{tag}>" + "".join(f"<li>{inline(x)}</li>" for x in items) + f"</{tag}>"); continue
        if line.startswith("```"):
            code = []; i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                code.append(lines[i]); i += 1
            i += 1; out.append("<pre><code>" + html.escape("\n".join(code)) + "</code></pre>"); continue
        para = [line]; i += 1
        while i < len(lines) and lines[i].strip() and not re.match(r"^(#{1,4} |- |\d+\. |\||```|-{3,}\s*$)", lines[i]):
            para.append(lines[i]); i += 1
        out.append(f"<p>{inline(' '.join(para))}</p>")
    return "\n".join(out)


def page(title: str, body: str, crumbs: bool = True) -> str:
    nav = f'<nav><a href="./">Internal docs</a> · {html.escape(PROJECT)}</nav>' if crumbs else ""
    return (f'<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">'
            f'<meta name="robots" content="noindex"><title>{html.escape(title)}</title>'
            f'<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Fraunces:wght@500&family=Geist:wght@400;500;600&family=Azeret+Mono&display=swap">'
            f"<style>{CSS}</style></head><body><div class=\"wrap\">{nav}{body}"
            f"<footer>Internal — not part of the customer deployment · rendered {date.today().isoformat()} from the repository documents</footer></div></body></html>")


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    links = []
    for name, src, label in PAGES:
        if not src.exists():
            continue
        md = src.read_text(encoding="utf-8")
        body = render_md(md)
        heads = re.findall(r'<h2 id="([^"]+)">(.*?)</h2>', body)
        if len(heads) > 40:        # a long log: newest first at the top, then a contents list
            toc = "<p><b>%d entries, newest last.</b> Jump to one:</p><ol class=\"toc\">" % len(heads) + "".join(
                f'<li><a href="#{i}">{t}</a></li>' for i, t in reversed(heads)) + "</ol><hr>"
            body = toc + body
        (OUT / name).write_text(page(label, body), encoding="utf-8")
        links.append((name, label, src.name))
    for name, src, label in COPIES:
        if not src.exists():
            continue
        raw = src.read_text(encoding="utf-8")
        if "charset" not in raw[:600].lower():   # a generated page relies on its host for the charset; give it one
            raw = '<meta charset="utf-8">\n' + raw
        (OUT / name).write_text(raw, encoding="utf-8")
        links.append((name, label, src.name))
    index = f"<h1>Internal docs</h1><p>Testing material for {html.escape(OWNER)}. Not part of a customer hand-off.</p><div class=\"index\">" + "".join(
        f'<a href="{n}">{html.escape(l)}<small><code>{s}</code></small></a>' for n, l, s in links) + "</div>"
    (OUT / "index.html").write_text(page(f"Internal docs — {PROJECT}", index, crumbs=False), encoding="utf-8")
    print(f"rendered {len(links)} pages → {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
